create schema if not exists private;

revoke all on schema private from public;
revoke all on schema private from anon;
revoke all on schema private from authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Coder',
  username text unique,
  avatar_url text,
  daily_goal_xp integer not null default 50 check (daily_goal_xp between 10 and 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.courses (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  description text not null default '',
  language text not null,
  accent text,
  sort_order integer not null default 0,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.units (
  id uuid primary key default gen_random_uuid(),
  course_id uuid not null references public.courses(id) on delete cascade,
  slug text not null,
  title text not null,
  description text not null default '',
  theme text,
  sort_order integer not null default 0,
  is_published boolean not null default false,
  unique (course_id, slug)
);

create table if not exists public.lessons (
  id uuid primary key default gen_random_uuid(),
  unit_id uuid not null references public.units(id) on delete cascade,
  slug text not null unique,
  title text not null,
  subtitle text not null default '',
  lesson_type text not null default 'lesson'
    check (lesson_type in ('lesson', 'checkpoint', 'project', 'practice')),
  icon text,
  xp_reward integer not null default 20 check (xp_reward >= 0),
  duration_minutes integer not null default 5 check (duration_minutes > 0),
  sort_order integer not null default 0,
  is_published boolean not null default false
);

create table if not exists public.exercises (
  id uuid primary key default gen_random_uuid(),
  lesson_id uuid not null references public.lessons(id) on delete cascade,
  exercise_key text not null unique,
  exercise_type text not null
    check (exercise_type in ('choice', 'text', 'code', 'order', 'debug')),
  eyebrow text not null default '',
  prompt text not null,
  code_snippet text,
  options jsonb,
  placeholder text,
  hint text,
  explanation text,
  sort_order integer not null default 0,
  is_published boolean not null default false
);

create table if not exists private.exercise_answers (
  exercise_id uuid primary key references public.exercises(id) on delete cascade,
  accepted_answers jsonb not null,
  correct_feedback text not null,
  incorrect_feedback text not null
);

create table if not exists public.user_lesson_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id uuid not null references public.lessons(id) on delete cascade,
  status text not null default 'available'
    check (status in ('locked', 'available', 'in_progress', 'completed')),
  attempts integer not null default 0 check (attempts >= 0),
  best_score numeric(5,2) not null default 0 check (best_score between 0 and 100),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

create table if not exists public.exercise_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exercise_id uuid not null references public.exercises(id) on delete cascade,
  submitted_answer jsonb not null,
  is_correct boolean,
  attempted_at timestamptz not null default now()
);

create table if not exists public.xp_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount integer not null check (amount <> 0),
  event_type text not null,
  lesson_id uuid references public.lessons(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists units_course_sort_idx on public.units(course_id, sort_order);
create index if not exists lessons_unit_sort_idx on public.lessons(unit_id, sort_order);
create index if not exists exercises_lesson_sort_idx on public.exercises(lesson_id, sort_order);
create index if not exists lesson_progress_user_idx on public.user_lesson_progress(user_id, status);
create index if not exists exercise_attempts_user_idx on public.exercise_attempts(user_id, attempted_at desc);
create index if not exists xp_events_user_idx on public.xp_events(user_id, created_at desc);

