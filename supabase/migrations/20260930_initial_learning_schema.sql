insert into private.exercise_answers (
  exercise_id, accepted_answers, correct_feedback, incorrect_feedback
)
select e.id,
  case e.exercise_key
    when 'hello-print-choice' then '["print(\"Hello, coder!\")"]'::jsonb
    when 'hello-fill-print' then '["print"]'::jsonb
    when 'hello-output' then '["Python is fun"]'::jsonb
    when 'variable-create' then '["score = 10"]'::jsonb
    when 'variable-name' then '["lives"]'::jsonb
    when 'variable-output' then '["7"]'::jsonb
    when 'variable-code' then '["language=\"Python\"","language=''Python''"]'::jsonb
  end,
  case
    when e.exercise_key like 'hello-%' then 'Correct — you are getting the hang of Python output.'
    else 'Correct — that variable works.'
  end,
  case
    when e.exercise_key like 'hello-%' then 'Look again at how Python prints text.'
    else 'Follow the variable-name = value pattern and try again.'
  end
from public.exercises e
where e.exercise_key in (
  'hello-print-choice',
  'hello-fill-print',
  'hello-output',
  'variable-create',
  'variable-name',
  'variable-output',
  'variable-code'
)
on conflict (exercise_id) do nothing;
