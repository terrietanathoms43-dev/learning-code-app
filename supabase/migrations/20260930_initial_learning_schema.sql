create policy "published courses are readable"
on public.courses for select
to anon, authenticated
using (is_published);

create policy "published units are readable"
on public.units for select
to anon, authenticated
using (
  is_published
  and exists (
    select 1 from public.courses c
    where c.id = units.course_id and c.is_published
  )
);

create policy "published lessons are readable"
on public.lessons for select
to anon, authenticated
using (
  is_published
  and exists (
    select 1
    from public.units u
    join public.courses c on c.id = u.course_id
    where u.id = lessons.unit_id
      and u.is_published
      and c.is_published
  )
);

create policy "published exercises are readable"
on public.exercises for select
to anon, authenticated
using (
  is_published
  and exists (
    select 1
    from public.lessons l
    join public.units u on u.id = l.unit_id
    join public.courses c on c.id = u.course_id
    where l.id = exercises.lesson_id
      and l.is_published
      and u.is_published
      and c.is_published
  )
);

create policy "users can read own profile"
on public.profiles for select
to authenticated
using ((select auth.uid()) = id);

create policy "users can update own profile"
on public.profiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

create policy "users can read own progress"
on public.user_lesson_progress for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "users can read own attempts"
on public.exercise_attempts for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "users can read own xp"
on public.xp_events for select
to authenticated
using ((select auth.uid()) = user_id);

